#!/usr/bin/env python3
"""Generate harness/run_tests.mcfunction from the functions in a tests pack.

Every .mcfunction under data/<tests namespace>/function/ is a test, except the
ones in the `harness/` and `assert/` folders (kept for the pack's own helpers;
the shared ones live in ARMOUR's `armour` harness pack). Adding a test file is
all it takes to get it run: there is no list to maintain.

The harness finds the runner through the function tag `#armour:run_tests`, so
this script also writes that tag file into the tests pack, pointing at the
runner it just generated.

Usage:
  generate_test_runner.py [tests_pack_dir] [--repo .]   (default dir: tests)

The tests namespace comes from the repo's armour.json (see armour_config.py).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import TYPE_CHECKING

import armour_config
from armour_common import ArmourError, run

if TYPE_CHECKING:
    from collections.abc import Sequence

NON_TEST_FOLDERS = frozenset({"harness", "assert"})
# Where the test functions run: the arena test position (see armour:harness/run).
TEST_POSITION = "8 150 8"


def find_tests(pack_dir: Path, namespace: str) -> list[str]:
    """Return the test function names (such as `group/name`), sorted."""
    function_dir = pack_dir / "data" / namespace / "function"
    tests = []
    for path in sorted(function_dir.rglob("*.mcfunction")):
        relative = path.relative_to(function_dir)
        # `parts[0]` still has its extension when the file sits directly in
        # function/, so only a *folder* named harness/assert excludes a file.
        if relative.parts[0] in NON_TEST_FOLDERS:
            continue
        tests.append(relative.with_suffix("").as_posix())
    return tests


def render(tests: Sequence[str], namespace: str) -> str:
    """Return the text of run_tests.mcfunction for these tests."""
    harness = armour_config.HARNESS_NAMESPACE
    lines = [
        (
            "## GENERATED by ARMOUR (scripts/generate_test_runner.py). "
            "Do not edit by hand."
        ),
        (
            f"## Runs each of the {len(tests)} test functions in this pack, "
            "one after the other."
        ),
        "",
    ]
    for test in tests:
        lines += [
            f'data modify storage armour:run name set value "{test}"',
            f"function {harness}:harness/begin_test",
            f"execute positioned {TEST_POSITION} run function {namespace}:{test}",
            f"function {harness}:harness/end_test",
            "",
        ]
    return "\n".join(lines)


def generate(pack_dir: Path, namespace: str) -> int:
    """Write the runner into `pack_dir` and return how many tests it runs."""
    tests = find_tests(pack_dir, namespace)
    if not tests:
        msg = f"No test functions found under {pack_dir}"
        raise ArmourError(msg)
    target = (
        pack_dir / "data" / namespace / "function" / "harness" / "run_tests.mcfunction"
    )
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(tests, namespace), encoding="utf-8", newline="\n")
    write_run_tests_tag(pack_dir, namespace)
    return len(tests)


def write_run_tests_tag(pack_dir: Path, namespace: str) -> None:
    """Point the harness's `#armour:run_tests` tag at this pack's runner."""
    tag = (
        pack_dir
        / "data"
        / armour_config.HARNESS_NAMESPACE
        / "tags"
        / "function"
        / "run_tests.json"
    )
    tag.parent.mkdir(parents=True, exist_ok=True)
    values = {"values": [f"{namespace}:harness/run_tests"]}
    tag.write_text(json.dumps(values, indent="\t") + "\n", encoding="utf-8")


def main(argv: Sequence[str] | None = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("tests_dir", nargs="?", default="tests")
    parser.add_argument(
        "--repo", default=".", help="repository root (contains armour.json)"
    )
    args = parser.parse_args(argv)
    config = armour_config.load(Path(args.repo).resolve())
    pack = Path(args.tests_dir)
    print(f"Generated {pack}: {generate(pack, config.tests_namespace)} tests")
    return 0


if __name__ == "__main__":
    raise SystemExit(run(main))
